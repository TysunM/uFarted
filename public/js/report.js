// Printable 90-day summary for doctor visits.
import { TRIGGERS, SMELL, DISCOMFORT, HEALTH, typeInfo } from './catalog.js';
import { el, append, localDate, shortDate, hourLabel } from './ui.js';
import { api } from './api.js';
import { dailyChart, hourChart, gutChart } from './views/insights.js';

const root = document.getElementById('report');
try {
  const [{ user, config }, s] = await Promise.all([api('/me'), api(`/stats?today=${localDate()}&days=90`)]);
  const tracked = s.daily.filter((d) => d.fart + d.burp > 0);
  const avg = (k) => (tracked.length ? (tracked.reduce((n, d) => n + d[k], 0) / tracked.length).toFixed(1) : '—');
  const max = (k) => Math.max(0, ...s.daily.map((d) => d[k]));
  const peak = s.hours.some(Boolean) ? hourLabel(s.hours.indexOf(Math.max(...s.hours))) : '—';
  const row = (...cells) => el('tr', {}, cells.map((c) => el('td', {}, c)));
  const table = (head, rows) => el('table', {}, el('thead', {}, el('tr', {}, head.map((h) => el('th', {}, h)))), el('tbody', {}, rows));
  document.title = `Gas report · ${config.appName}`;

  root.replaceChildren();
  append(root, [
    el('div', { class: 'row spread no-print' }, el('a', { href: '/#/insights' }, '← Back'), el('button', { class: 'btn primary sm', onclick: () => print() }, '🖨️ Print / save PDF')),
    el('h1', {}, 'Bloating & gas summary'),
    el('p', { class: 'muted' }, `${user.username ? `@${user.username} · ` : ''}${shortDate(s.daily[0].date)} – ${shortDate(s.today.date)} · ${tracked.length} days with entries · generated by ${config.appName}`),
    el('section', { class: 'card stack tight' }, el('h2', {}, 'Summary'),
      table(['Measure', 'Farts', 'Burps'], [
        row('Average per tracked day', avg('fart'), avg('burp')),
        row('Highest single day', max('fart'), max('burp')),
        row('Personal baseline (median of recent days)', s.baseline ? s.baseline.fart : '—', s.baseline ? s.baseline.burp : '—'),
        row('Typical population range (self-logged)', `${HEALTH.fart.low}–${HEALTH.fart.high}/day`, `up to ~${HEALTH.burp.high}/day`),
      ]),
      table(['Daily gut check', 'Value'], [
        row('Days checked in', `${s.gut.checkedDays} of ${s.days}`),
        row('Days with moderate/severe bloating', `${s.gut.bloatedDays}`),
        row('Days with moderate/severe belly pain', `${s.gut.painDays}`),
        row('Average bloating (0–3)', s.gut.avgBloating ?? '—'),
        row('Average belly pain (0–3)', s.gut.avgPain ?? '—'),
      ]),
      table(['Other', 'Value'], [
        row('Days with moderate/severe discomfort at time of gas', `${s.discomfortDays}`),
        row('Average smell rating', s.smellAvg == null ? '—' : `${s.smellAvg} / 4 (${SMELL[Math.round(s.smellAvg)].split(' ').slice(1).join(' ')})`),
        row('Most active hour', peak),
      ])),
    s.gut.checkedDays > 0 && el('section', { class: 'card stack tight' }, el('h2', {}, 'Bloating & belly pain'), gutChart(s.daily),
      el('p', { class: 'tiny muted' }, 'Purple = bloating, red = belly pain, each 0 (none) to 3 (severe). Empty = no check-in.')),
    el('section', { class: 'card stack tight' }, el('h2', {}, 'Daily counts'), dailyChart(s.daily),
      el('p', { class: 'tiny muted' }, 'Green = flatus, blue = belching.')),
    el('section', { class: 'card stack tight' }, el('h2', {}, 'Time of day'), hourChart(s.hours)),
    s.triggers?.length > 0 && el('section', { class: 'card stack tight' }, el('h2', {}, 'Self-tagged possible triggers'),
      table(['Trigger', 'Entries', 'Avg smell (0–4)', `With ${DISCOMFORT[2].toLowerCase()}+ discomfort`, 'Bloating on days with / without'],
        s.triggers.map((t) => row(TRIGGERS.find((x) => x.id === t.id).name, t.count, t.avgSmell ?? '—', t.discomfort,
          t.bloatWith == null ? '—' : `${t.bloatWith} / ${t.bloatWithout ?? '—'}`)))),
    s.topTypes.length > 0 && el('section', { class: 'card stack tight' }, el('h2', {}, 'Most frequent types'),
      table(['Type', 'Entries'], s.topTypes.map((t) => { const i = typeInfo(t.kind, t.type); return row(`${i.name} (${t.kind})`, t.count); }))),
    el('p', { class: 'tiny muted' }, 'Self-reported by the patient for discussion with a clinician. Not a diagnostic record. '
      + 'Reference: CSIRO 2026, JAMA Network Open — median 3.8 self-logged flatus events/day, 80% of adults 2–7/day.')]);
} catch (err) {
  root.replaceChildren(el('p', {}, err.status === 401 ? 'Please open the app and sign in first.' : 'Couldn’t load your report.'), el('a', { href: '/' }, 'Open app'));
}
